import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PgDialect } from "drizzle-orm/pg-core";
import { sql, type SQL } from "drizzle-orm";
import { homeRanges, localDate } from "../services/dateBuckets";
import { env } from "../env";
import { getHome, homeCandidatesQuery } from "../services/homeService";
import { getPortfolio, portfolioSql } from "../services/portfolioService";
import {
  activitySearchSql,
  peopleSearchSql,
  search,
  subprojectSearchSql,
} from "../services/searchService";
import { getWorkload, workloadSql } from "../services/workloadService";
import { portfolioQuerySchema } from "@myapp/shared";
import { assertLocalDatabase } from "./seedPerf";
import { db, pool } from "./client";

/**
 * Runs EXPLAIN (ANALYZE, BUFFERS) for the app's own read queries, exactly as the app builds them, and times the
 * service calls. Writes docs/db-plans.md. Local development only; run it after `npm run db:seed:perf`.
 */
const dialect = new PgDialect();

async function plan(label: string, query: { sql: string; params: unknown[] }): Promise<string> {
  const res = await pool.query<{ "QUERY PLAN": string }>(
    `EXPLAIN (ANALYZE, BUFFERS) ${query.sql}`,
    query.params,
  );
  const text = res.rows.map((r) => r["QUERY PLAN"]).join("\n");
  const seqOnActivities = /Seq Scan on activities\b/.test(text);
  return [
    `### ${label}`,
    "",
    seqOnActivities
      ? "**Sequential scan on `activities` present.**"
      : "No sequential scan on `activities`.",
    "",
    "```",
    text,
    "```",
    "",
  ].join("\n");
}

const fromSql = (s: SQL) => {
  const q = dialect.sqlToQuery(s);
  return { sql: q.sql, params: q.params };
};

async function time(label: string, fn: () => Promise<unknown>, runs = 7): Promise<string> {
  await fn(); // warm up the plan cache and buffers
  const samples: number[] = [];
  for (let i = 0; i < runs; i += 1) {
    const start = performance.now();
    await fn();
    samples.push(performance.now() - start);
  }
  samples.sort((a, b) => a - b);
  const median = samples[Math.floor(samples.length / 2)] ?? 0;
  return `| ${label} | ${median.toFixed(1)} ms | ${(samples.at(-1) ?? 0).toFixed(1)} ms |`;
}

async function main(): Promise<void> {
  assertLocalDatabase();
  const now = new Date();
  const today = localDate(now, env.APP_TIMEZONE);
  const r = homeRanges(today);

  const pmRow = (
    await db.execute<{ id: string }>(
      sql`SELECT id FROM users WHERE role = 'pm' ORDER BY created_at LIMIT 1`,
    )
  ).rows[0];
  const memberRow = (
    await db.execute<{ id: string }>(sql`
      SELECT assignee_id AS id FROM activities WHERE assignee_id IS NOT NULL GROUP BY assignee_id ORDER BY count(*) DESC LIMIT 1`)
  ).rows[0];
  if (!pmRow || !memberRow) throw new Error("Seed the database first");
  const pm = { id: pmRow.id, role: "pm" as const, fullName: "PM" };
  const member = { id: memberRow.id, role: "team_member" as const, fullName: "Member" };

  const counts = (
    await db.execute<{ activities: number; events: number }>(sql`
      SELECT (SELECT count(*) FROM activities)::int AS activities, (SELECT count(*) FROM activity_events)::int AS events`)
  ).rows[0];

  const plans = [
    await plan("Home, project manager (all activities)", homeCandidatesQuery(pm, {}, r).toSQL()),
    await plan("Home, team member (own activities)", homeCandidatesQuery(member, {}, r).toSQL()),
    await plan("Portfolio", fromSql(portfolioSql(today, pm.id))),
    await plan("Workload", fromSql(workloadSql(r.weekStart, r.weekEnd))),
    await plan(
      "Search: activities, term `engagement`",
      fromSql(activitySearchSql("engagement", 8)),
    ),
    await plan(
      "Search: activities, partial word `dashbo`",
      fromSql(activitySearchSql("dashbo", 8)),
    ),
    await plan("Search: subprojects", fromSql(subprojectSearchSql("analytics", 8))),
    await plan("Search: people", fromSql(peopleSearchSql("ana", 8))),
  ];

  const timings = [
    await time("Home (PM)", () => getHome(pm, { now })),
    await time("Home (team member)", () => getHome(member, { now })),
    await time("Portfolio", () => getPortfolio(pm, portfolioQuerySchema.parse({}), now)),
    await time("Workload", () => getWorkload({ now })),
    await time("Search `engagement`", () => search("engagement")),
    await time("Search `dashbo`", () => search("dashbo")),
  ];

  const out = [
    "# Query plans and timings (generated)",
    "",
    `Generated by \`npm run db:explain -w @myapp/backend\` on ${now.toISOString()}.`,
    `Data: ${counts?.activities ?? "?"} activities, ${counts?.events ?? "?"} activity events (perf seed). Do not edit by hand; rerun the command.`,
    "",
    "## Server time per service call (median and worst of 7 runs, after a warm-up)",
    "",
    "| Call | Median | Worst |",
    "| --- | --- | --- |",
    ...timings,
    "",
    "## EXPLAIN (ANALYZE, BUFFERS)",
    "",
    ...plans,
  ].join("\n");
  writeFileSync(new URL("../../../../docs/db-plans.md", import.meta.url), out + "\n");
  process.stdout.write(`${timings.join("\n")}\n`);
  for (const p of plans) {
    const verdict = p.includes("**Sequential scan") ? "SEQ SCAN ON ACTIVITIES" : "ok";
    process.stdout.write(`${p.split("\n")[0] ?? ""} -> ${verdict}\n`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main()
    .catch((err: unknown) => {
      process.stderr.write(`${err instanceof Error ? (err.stack ?? err.message) : String(err)}\n`);
      process.exitCode = 1;
    })
    .finally(() => {
      void pool.end();
    });
}
